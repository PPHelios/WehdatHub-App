// scripts/sync-chat-domain.mjs — Copies the WhatsApp chat reader (parse + match) from the server repo into the shared package,
// so the website and the app read a chat export with the SAME code. The server's domain/chatParse.js and domain/chatMatch.js
// are the source of truth; edit them there, then run:  node scripts/sync-chat-domain.mjs   (from the app repo root)
// --check exits 1 when the copies are out of date (the shared package's test runs the same comparison when the server repo is next to this one).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const server = path.join(root, '..', 'WehdatHub-Server', 'domain');
const out = path.join(root, 'packages', 'shared', 'src', 'chat');

// The server files are UMD (they run in the browser and in Node). Here they run inside a small wrapper that gives them
// `module` and `require`, so React Native and the tests load them as plain ES modules.
const wrap = (name, source, imports) => `// @ts-nocheck
// GENERATED by scripts/sync-chat-domain.mjs from WehdatHub-Server/domain/${name}.js. Do not edit here: change the server file and run the script.
${imports}
const __m = { exports: {} };
((module, require) => {
${source}
})(__m, (n) => __deps[n]);
export default __m.exports;
`;

const files = [
  { name: 'chatParse', imports: 'const __deps = {};' },
  { name: 'chatMatch', imports: "import ChatParse from './chatParse';\nconst __deps = { './chatParse': ChatParse };" },
];
let stale = false;
for (const f of files) {
  const source = fs.readFileSync(path.join(server, `${f.name}.js`), 'utf8').replace(/\r\n/g, '\n');
  const next = wrap(f.name, source, f.imports);
  const target = path.join(out, `${f.name}.ts`);
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== next) { console.error(`${f.name}.ts is out of date`); stale = true; }
  } else {
    fs.writeFileSync(target, next);
    console.log(`wrote ${path.relative(root, target)}`);
  }
}
if (stale) process.exit(1);
